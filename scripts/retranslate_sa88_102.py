# validate_restyle 的「五阴齐备」检查触发条件是「源文同时出现 色 与 识」。
# SA_94／SA_95 属婆罗门相应，其「识」出自「善知识」、「色」出自「色泽／本生色」，
# 并非五阴法数；强填五蕴反伤「信」。故仅将该项误报降级记录，不改译文。
NON_AGGREGATE_SUTTAS = {"SA_94", "SA_95"}


def _confidence_from_notes(notes: str) -> tuple[str, str]:
    """与 scripts/merge_all_gold.py 的推导保持一致。"""
    if "gold_reconstructed" in notes or "不作臆造" in notes or "仅作交叉" in notes:
        return "gold_reconstructed", "low"
    if "confidence=medium" in notes or "无可靠" in notes:
        return "gold", "medium"
    return "gold", "high"


def _check_paragraph_parity() -> list[str]:
    bad = []
    for rid, g in GOLD.items():
        lit = g["kumarajiva_style_text"].split("\n")
        mod = g["modern_psychology_text"].split("\n")
        if len(lit) != len(mod):
            bad.append(f"{rid}: literary={len(lit)} modern={len(mod)}")
    return bad


def main() -> None:
    parity = _check_paragraph_parity()
    if parity:
        raise SystemExit("paragraph parity broken:\n" + "\n".join(parity))

    aligned = ROOT / "data" / "aligned" / "raw_aligned_data.json"
    out = ROOT / "data" / "translated" / "final_translated_data.json"
    gold_dir = ROOT / "data" / "golden"
    gold_dir.mkdir(parents=True, exist_ok=True)

    if out.exists():
        records = json.loads(out.read_text(encoding="utf-8"))
        by_id = {r["id"]: r for r in records}
        for r in json.loads(aligned.read_text(encoding="utf-8")):
            by_id.setdefault(r["id"], r)
        records = sorted(by_id.values(), key=lambda x: int(x["id"].split("_")[1]))
    else:
        records = json.loads(aligned.read_text(encoding="utf-8"))

    report = []
    merged = []
    for rec in records:
        rid = rec["id"]
        item = dict(rec)
        if rid in GOLD:
            g = GOLD[rid]
            item["kumarajiva_style_text"] = g["kumarajiva_style_text"]
            item["modern_psychology_text"] = g["modern_psychology_text"]
            item["notes"] = g["notes"]
            item["translator"] = "cursor-agent"
            status, conf = _confidence_from_notes(g["notes"])
            item["review_status"] = status
            item["confidence"] = conf

            v = validate_restyle(
                item.get("chinese_text") or "",
                item["kumarajiva_style_text"],
                item["modern_psychology_text"],
            )
            suppressed: list[str] = []
            if rid in NON_AGGREGATE_SUTTAS:
                keep = [i for i in v["issues"] if not i.startswith("missing_aggregate:")]
                suppressed = [i for i in v["issues"] if i.startswith("missing_aggregate:")]
                if suppressed:
                    v = dict(v)
                    v["issues"] = keep
                    v["suppressed_false_positives"] = suppressed
                    v["status"] = "ok" if not keep and not v["warnings"] else ("fail" if keep else "warn")

            item["validation"] = v
            item["forbidden_hits"] = v.get("forbidden_hits") or []
            sim = similarity_to_source(item.get("chinese_text") or "", item["kumarajiva_style_text"])
            item["similarity_to_source"] = round(sim, 3)
            if v["status"] == "fail":
                item["review_status"] = "needs_doctrine_check"
            report.append(
                {
                    "id": rid,
                    **v,
                    "sim": round(sim, 3),
                    "confidence": item.get("confidence"),
                }
            )
            (gold_dir / f"{rid.lower()}.json").write_text(
                json.dumps(item, ensure_ascii=False, indent=2), encoding="utf-8"
            )
        merged.append(item)

    out.write_text(json.dumps(merged, ensure_ascii=False, indent=2), encoding="utf-8")
    web = ROOT / "web" / "public" / "final_translated_data.json"
    if web.parent.exists():
        web.write_text(out.read_text(encoding="utf-8"), encoding="utf-8")
    (ROOT / "data" / "translated" / "validation_report_sa88-102.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    fails = [r for r in report if r["status"] == "fail"]
    warns = [r for r in report if r["status"] == "warn"]
    oks = [r for r in report if r["status"] == "ok"]
    print(f"merged total={len(merged)} retranslated={len(GOLD)} (SA_88–102 only)")
    print(f"validation: ok={len(oks)} warn={len(warns)} fail={len(fails)}")
    for r in report:
        print(
            r["id"],
            r["status"],
            f"sim={r['sim']}",
            f"conf={r['confidence']}",
            r.get("issues"),
            r.get("warnings"),
            r.get("suppressed_false_positives") or "",
        )


if __name__ == "__main__":
    main()
