def main() -> None:
    out = ROOT / "data" / "translated" / "final_translated_data.json"
    web = ROOT / "web" / "public" / "final_translated_data.json"
    gold_dir = ROOT / "data" / "golden"
    gold_dir.mkdir(parents=True, exist_ok=True)

    records = json.loads(out.read_text(encoding="utf-8"))
    report: list[dict] = []
    by_id = {r["id"]: r for r in records}

    for rid, g in GOLD.items():
        if rid not in by_id:
            raise SystemExit(f"missing record {rid}")
        item = by_id[rid]
        item["kumarajiva_style_text"] = g["kumarajiva_style_text"]
        item["modern_psychology_text"] = g["modern_psychology_text"]
        item["notes"] = g["notes"]
        item["review_status"] = "gold"
        item["translator"] = "cursor-agent"
        item["confidence"] = g.get("confidence", "high")
        item["revision_reason"] = None

        v = validate_restyle(
            item["chinese_text"],
            item["kumarajiva_style_text"],
            item["modern_psychology_text"],
        )
        item["validation"] = v
        item["forbidden_hits"] = v.get("forbidden_hits") or []
        if v["status"] == "fail":
            item["review_status"] = "needs_doctrine_check"
        report.append({"id": rid, **v, "confidence": item["confidence"]})

        (gold_dir / f"{rid.lower()}.json").write_text(
            json.dumps(item, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

    payload = json.dumps(records, ensure_ascii=False, indent=2) + "\n"
    out.write_text(payload, encoding="utf-8")
    web.parent.mkdir(parents=True, exist_ok=True)
    web.write_text(payload, encoding="utf-8")

    fails = [r for r in report if r["status"] == "fail"]
    warns = [r for r in report if r["status"] == "warn"]
    oks = [r for r in report if r["status"] == "ok"]
    print(f"Wrote {len(GOLD)} gold sutras → {out}")
    print(f"Also → {web}")
    print(f"Golden files → {gold_dir}/sa_1.json … sa_16.json")
    print(f"validation: ok={len(oks)} warn={len(warns)} fail={len(fails)}")
    for r in report:
        flag = r["status"]
        extra = ""
        if r.get("issues"):
            extra += f" issues={r['issues']}"
        if r.get("warnings"):
            extra += f" warnings={r['warnings']}"
        print(f"  {r['id']}: {flag}{extra}")


if __name__ == "__main__":
    main()
