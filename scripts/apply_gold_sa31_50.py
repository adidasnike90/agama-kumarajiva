def main() -> None:
    aligned = ROOT / "data" / "aligned" / "raw_aligned_data.json"
    out = ROOT / "data" / "translated" / "final_translated_data.json"
    gold_dir = ROOT / "data" / "golden"
    gold_dir.mkdir(parents=True, exist_ok=True)

    # Prefer existing translated (keeps SA1–30 gold) else aligned
    if out.exists():
        records = json.loads(out.read_text(encoding="utf-8"))
        by_id = {r["id"]: r for r in records}
        for r in json.loads(aligned.read_text(encoding="utf-8")):
            by_id.setdefault(r["id"], r)
        records = sorted(by_id.values(), key=lambda x: int(x["id"].split("_")[1]))
    else:
        records = json.loads(aligned.read_text(encoding="utf-8"))

    report = []
    merged = []
    for rec in records:
        rid = rec["id"]
        item = dict(rec)
        if rid in GOLD:
            g = GOLD[rid]
            item["kumarajiva_style_text"] = g["kumarajiva_style_text"]
            item["modern_psychology_text"] = g["modern_psychology_text"]
            item["notes"] = g["notes"]
            item["review_status"] = "gold"
            item["translator"] = "cursor-agent"
            if rid == "SA_40":
                item["confidence"] = "medium"
                item["review_status"] = "gold_reconstructed"
            else:
                item["confidence"] = "high"
            v = validate_restyle(
                item["chinese_text"],
                item["kumarajiva_style_text"],
                item["modern_psychology_text"],
            )
            item["validation"] = v
            item["forbidden_hits"] = v.get("forbidden_hits") or []
            if v["status"] == "fail" and rid != "SA_40":
                item["review_status"] = "needs_doctrine_check"
            report.append({"id": rid, **v, "confidence": item.get("confidence")})
            (gold_dir / f"{rid.lower()}.json").write_text(
                json.dumps(item, ensure_ascii=False, indent=2), encoding="utf-8"
            )
        merged.append(item)

    out.write_text(json.dumps(merged, ensure_ascii=False, indent=2), encoding="utf-8")
    web = ROOT / "web" / "public" / "final_translated_data.json"
    web.write_text(out.read_text(encoding="utf-8"), encoding="utf-8")
    (ROOT / "data" / "translated" / "validation_report_sa31-50.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    fails = [r for r in report if r["status"] == "fail"]
    warns = [r for r in report if r["status"] == "warn"]
    print(f"merged total={len(merged)} new_gold={len(GOLD)}")
    print(f"validation: ok={len(report)-len(fails)-len(warns)} warn={len(warns)} fail={len(fails)}")
    for r in report:
        if r["status"] != "ok":
            print(r["id"], r["status"], r.get("issues"), r.get("warnings"))


if __name__ == "__main__":
    main()
