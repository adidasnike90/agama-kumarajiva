    mod = f"阎浮车问舍利弗：「{q}」舍利弗回答：「{a}」"
    if extra_before_path:
        lit += extra_before_path[0]
        mod += extra_before_path[1]
    lit += (
        f"复问：「{path_q}」"
        f"舍利弗言：「{EIGHTFOLD_LIT}」{JAMBU_CLOSE_LIT}"
    )
    mod += (
        f"又问：「{path_q}」"
        f"舍利弗说：「{EIGHTFOLD_MOD}」{JAMBU_CLOSE_MOD}"
    )
    return lit, mod


